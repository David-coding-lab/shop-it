type Props = { variant?: WaveVariant };

export function waveHeight(variant: WaveVariant, screenWidth: number) {
  return (screenWidth * VARIANTS[variant].height) / VIEW_W;
}

export default function WaveHeader({ variant = "welcome" }: Props) {
  const { width } = useWindowDimensions();
  const v = VARIANTS[variant];
  const id = `waveClip-${variant}`;

  const contours = useMemo(
    () =>
      CLUSTERS.flatMap(([cx, cy, rx, ry, rings, step, seed], c) =>
        Array.from({ length: rings }, (_, i) =>
          ringPath(cx, cy, rx + i * step, ry + i * step, seed + i * 0.18),
        ).map((d, i) => ({ d, key: `${c}-${i}` })),
      ),
    [],
  );

  return (
    <Svg
      width={width}
      height={waveHeight(variant, width)}
      viewBox={`0 0 ${VIEW_W} ${v.height}`}
      style={{ position: "absolute", top: 0, left: 0 }}
    >
      <Defs>
        <ClipPath id={id}>
          <Path d={v.shape} />
        </ClipPath>
      </Defs>

      <Path d={v.shape} fill={PURPLE} />

      <G clipPath={`url(#${id})`}>
        <Image
          href={TEXTURE}
          x={v.texture.x}
          y={v.texture.y}
          width={TEXTURE_W}
          height={TEXTURE_H}
          opacity={0.2}
          preserveAspectRatio="none"
        />
        {contours.map(({ d, key }) => (
          <Path
            key={key}
            d={d}
            fill="none"
            stroke="#FFFFFF"
            strokeOpacity={0.16}
            strokeWidth={1.4}
          />
        ))}
        {v.icons.map(([i, tx, ty]) => (
          <Path
            key={i}
            d={ICONS[i]}
            transform={`translate(${tx} ${ty})`}
            fill="#DBEAFE"
            fillOpacity={0.17}
          />
        ))}
      </G>
    </Svg>
  );
}
